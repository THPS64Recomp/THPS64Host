"""Generate the N64Recomp inputs: a code blob and a syms.toml.

The code blob is what the game has in RDRAM after boot (Conker-recomp
pattern): the boot segment (ROM 0x1000-0x13B10 -> 0x80000400) followed by the
ERZ-inflated main image (-> 0x80016AC0). It is ROM-derived and is written to
build/ only. The syms.toml holds only addresses, sizes and names.

usage: python decomp/common/gen_syms.py --game thps2 baserom.z64 baserom.main.bin build/thps2.codeblob.bin recomp/thps2.syms.toml
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import funclist as F  # noqa: E402
import thpsgame  # noqa: E402

# blob = ROM header+IPL3 (0x1000) | boot segment | main image.
# N64Recomp requires the entrypoint function at rom 0x1000, as in a real ROM.
BOOT_BLOB_OFF = 0x1000


def main(g, rom_p, img_p, blob_p, toml_p):
    MAIN_BLOB_OFF = g.main_blob_off
    boot, main_, fb, fm, syms = F.load_all(rom_p, img_p, g=g)
    os.makedirs(os.path.dirname(blob_p) or ".", exist_ok=True)
    rom = open(rom_p, "rb").read()
    open(blob_p, "wb").write(rom[:BOOT_BLOB_OFF] + boot.data + main_.data)

    def blob_off(vram):
        if vram < F.MAIN_VRAM:
            return BOOT_BLOB_OFF + vram - F.BOOT_VRAM
        return MAIN_BLOB_OFF + vram - F.MAIN_VRAM

    sections = []
    for img, funcs, ranges, tag in ((boot, fb, F.BOOT_TEXT, "boot"), (main_, fm, F.MAIN_TEXT, "main")):
        for k, (lo, hi) in enumerate(ranges):
            fs = sorted((a, s) for a, s in funcs.items() if lo <= a < hi)
            sections.append((f".{tag}_text{k}", lo, hi, fs))

    used, n_named, n_total = set(), 0, 0
    out = [f"# {g.title} symbols for N64Recomp (generated by decomp/common/gen_syms.py).",
           f"# rom = offset into build/{g.name}.codeblob.bin: ROM 0x0-0x1000 | boot segment |",
           "# inflated main image (so the boot entry sits at rom 0x1000 like the real ROM).",
           "# Names: symbols/boot.txt + symbols/main.txt; everything else func_<VRAM>.", ""]
    for name, lo, hi, fs in sections:
        out += ["[[section]]", f'name = "{name}"', f"rom = 0x{blob_off(lo):X}",
                f"vram = 0x{lo:08X}", f"size = 0x{hi - lo:X}", "", "functions = ["]
        for a, s in fs:
            nm = syms.get(a, f"func_{a:08X}")
            if nm in used:
                nm = f"{nm}_{a:08X}"
            used.add(nm)
            n_named += a in syms
            n_total += 1
            out.append(f'    {{ name = "{nm}", vram = 0x{a:08X}, size = 0x{s:X} }},')
        out += ["]", ""]
    os.makedirs(os.path.dirname(toml_p) or ".", exist_ok=True)
    open(toml_p, "w").write("\n".join(out))
    print(f"{toml_p}: {len(sections)} sections, {n_total} functions, {n_named} named")


if __name__ == "__main__":
    g, args = thpsgame.from_argv(sys.argv[1:])
    main(g, *args[:4])
