#!/usr/bin/env python3
"""Does the C++ first-run overlay module reproduce the static build's Python output? (needs the ROMs: local only)

For each class (thps2/us, thps2/eu, thps3/us) the test:
  1. makes the REFERENCE with the static build's tools: the code blob (unpack + header), gen_host_syms.py, overlay_recomp.py
     (blob + syms + overlay table), exactly as decomp/thps2/recomp-host/tools/gen.py and decomp/thps3/recomp-host/tools/gen.sh do;
  2. regenerates the recipe (gen_overlay_recipe.py) into a scratch dir and requires it to equal the committed recipe;
  3. runs overlay_rom_cli (overlay_rom.cpp) with the committed recipe + the ROM + the main code blob and requires
     blob.bin, syms.toml and the overlay table to be byte-identical to the reference
     (the table's first line is a "Generated by ..." comment in the Python output: skipped);
  4. negative cases: a modified overlay byte (refused by the fingerprint), a recipe-less stream damage (refused by the stream check),
     a truncated ROM;
  5. with --n64recomp: runs N64Recomp on the reference and on the C++ output and requires an identical RecompiledFuncs/ tree;
  6. with --scan: the ROM-free scan (32-byte windows of the ROM, the main blob and the overlay blob against the committed recipe).

usage: python3 -I decomp/common/firstrun/test_overlay_rom.py [--n64recomp /path/to/N64Recomp] [--scan] [--keep DIR] [CLASS ...]
"""
import filecmp
import glob
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
COMMON = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(COMMON))
sys.path.insert(0, COMMON)
sys.path.insert(0, HERE)
import gen_overlay_recipe as G  # noqa: E402
import thps_unpack  # noqa: E402
import thpsgame  # noqa: E402

PY = [sys.executable, "-I"]
FAILS = []


def check(ok, what):
    print(("PASS " if ok else "FAIL ") + what)
    if not ok:
        FAILS.append(what)


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def same_file(a, b):
    return os.path.getsize(a) == os.path.getsize(b) and filecmp.cmp(a, b, shallow=False)


def reference(cls, spec, g, rom, img, blob, work):
    """The static build's output for one class, in work/."""
    force = os.path.join(REPO, spec["force"])
    bp = os.path.join(work, "main.codeblob.bin")
    open(bp, "wb").write(blob)
    rp = os.path.join(work, "rom.z64")
    open(rp, "wb").write(rom)
    mp = os.path.join(work, "main.bin")
    open(mp, "wb").write(img)
    r = run(PY + [os.path.join(COMMON, "gen_host_syms.py"), "--force", force, os.path.join(REPO, spec["syms"]),
                  os.path.join(work, "ref.syms0.toml"), bp])
    assert r.returncode == 0, r.stderr
    cmd = PY + [os.path.join(COMMON, "overlay_recomp.py"), "--game", g.name, rp, mp, "--blob-in", bp,
                "--blob-out", os.path.join(work, "ref.blob.bin"), "--syms-in", os.path.join(work, "ref.syms0.toml"),
                "--syms-out", os.path.join(work, "ref.syms.toml"), "--table-out", os.path.join(work, "ref.table.inc")]
    if "overlay_force" in open(force).read():
        cmd += ["--force", force]
    r = run(cmd)
    assert r.returncode == 0, r.stdout + r.stderr
    return bp, rp


def n64recomp_config(cls, spec, work, name, blob, syms, outdir):
    """The class's N64Recomp config with the three file paths pointed at (blob, syms, outdir)."""
    game = spec["prefix"]   # thps2 / thps3: the shared host's tools/gen_versions.py writes the class's N64Recomp config for every game
    d = os.path.join(work, "cfgsrc")
    os.makedirs(d, exist_ok=True)
    host = os.path.join(REPO, "decomp", game, "recomp-host")
    r = run(PY + [os.path.join(host, "tools", "gen_versions.py"), "config", cls.split("/")[1], d])
    assert r.returncode == 0, r.stderr
    text = open(os.path.join(d, f"{game}.host.toml")).read()
    for key, val in (("rom_file_path", blob), ("symbols_file_path", syms), ("output_func_path", outdir)):
        text, n = re.subn(rf'^{key} = ".*"$', f'{key} = "{val}"', text, flags=re.M)
        assert n == 1, key
    p = os.path.join(work, name)
    open(p, "w").write(text)
    return p


def test_class(cls, a):
    spec = G.CLASSES[cls]
    g = thpsgame.load(spec["game"])
    print(f"== {cls} ({g.title})")
    rom_path = a.rom.get(cls) or G.find_rom(g)
    rom = open(rom_path, "rb").read()
    img = thps_unpack.unpack(rom, g)
    blob = rom[:g.main_blob_off] + img
    work = os.path.join(a.work, cls.replace("/", "_"))
    os.makedirs(work, exist_ok=True)
    bp, rp = reference(cls, spec, g, rom, img, blob, work)
    ref_blob, ref_syms, ref_table = (os.path.join(work, n) for n in ("ref.blob.bin", "ref.syms.toml", "ref.table.inc"))

    # 2. the committed recipe is what the generator makes now
    rdir = G.recipe_dir(cls)
    tmp_out = os.path.join(work, "recipe-regen")
    r = run(PY + [os.path.join(HERE, "gen_overlay_recipe.py"), cls, "--rom", rom_path, "--out", tmp_out, "--cli", a.cli])
    check(r.returncode == 0, f"{cls}: recipe generator runs" + ("" if r.returncode == 0 else "\n" + r.stdout + r.stderr))
    for f in sorted(os.listdir(os.path.join(tmp_out, cls))):
        check(os.path.exists(os.path.join(rdir, f)) and same_file(os.path.join(tmp_out, cls, f), os.path.join(rdir, f)),
              f"{cls}: committed recipe file {f} equals a fresh generation")
    check(same_file(os.path.join(rdir, f"{spec['prefix']}.host.syms.toml"), os.path.join(work, "ref.syms0.toml")),
          f"{cls}: recipe symbol file equals gen_host_syms.py output (the static build's syms0)")

    # 3. C++ vs Python
    out = os.path.join(work, "cpp")
    os.makedirs(out, exist_ok=True)
    recipe = os.path.join(rdir, "overlays.txt")
    r = run([a.cli, "build", "--recipe", recipe, "--rom", rp, "--blob", bp, "--syms", os.path.join(rdir, f"{spec['prefix']}.host.syms.toml"), "--out", out])
    check(r.returncode == 0, f"{cls}: overlay_rom_cli build ({r.stdout.strip()}{r.stderr.strip()})")
    check(same_file(os.path.join(out, "blob.bin"), ref_blob), f"{cls}: blob.bin == overlay_recomp.py --blob-out ({os.path.getsize(ref_blob):#x} bytes)")
    check(same_file(os.path.join(out, "syms.toml"), ref_syms), f"{cls}: syms.toml == overlay_recomp.py --syms-out ({os.path.getsize(ref_syms)} bytes)")
    ref_tab = open(ref_table).read().split("\n", 1)[1]
    check(open(os.path.join(out, "table.inc")).read() == ref_tab, f"{cls}: overlay table == overlay_recomp.py --table-out (without its comment line)")
    game, cname = cls.split("/")
    committed = open(os.path.join(REPO, "decomp", game, "recomp-host", "versions", cname, "overlay_table.inc")).read().split("\n", 1)[1]
    check(open(os.path.join(out, "table.inc")).read() == committed, f"{cls}: overlay table == the committed {game} versions/{cname}/overlay_table.inc")

    # 4. refusals (into a scratch dir: the good output above is used by step 5)
    out_bad = os.path.join(work, "cpp-bad")
    os.makedirs(out_bad, exist_ok=True)
    bad = bytearray(rom)
    first = int(re.search(r"^o \S+ (0x[0-9A-Fa-f]+)", open(recipe).read(), re.M).group(1), 16)
    bad[first + 0x40] ^= 0x55
    badp = os.path.join(work, "bad.z64")
    open(badp, "wb").write(bad)
    r = run([a.cli, "build", "--recipe", recipe, "--rom", badp, "--blob", bp, "--syms", ref_syms, "--out", out_bad])
    check(r.returncode == 2 and "modified dump" in r.stderr, f"{cls}: a changed overlay byte is refused by the fingerprint (exit {r.returncode})")
    nofp = os.path.join(work, "nofp.txt")
    open(nofp, "w").write(re.sub(r"^rom_xxh3 .*\n", "", open(recipe).read(), flags=re.M))
    r = run([a.cli, "build", "--recipe", nofp, "--rom", badp, "--blob", bp, "--syms", ref_syms, "--out", out_bad])
    check(r.returncode == 0, f"{cls}: without a fingerprint a byte change in a blob is not an error by itself (exit {r.returncode}); the main-blob check catches code changes")
    # damage the first relocation stream's terminator -> the stream no longer ends where the recipe says
    m = re.search(r"^o \S+ \S+ \S+ (0x[0-9A-Fa-f]+) (0x[0-9A-Fa-f]+)", open(recipe).read(), re.M)
    rel, rsize = int(m.group(1), 16), int(m.group(2), 16)
    bad2 = bytearray(rom)
    bad2[rel + rsize - 4:rel + rsize] = b"\x00\x00\x00\x00"
    open(badp, "wb").write(bad2)
    r = run([a.cli, "build", "--recipe", nofp, "--rom", badp, "--blob", bp, "--syms", ref_syms, "--out", out_bad])
    check(r.returncode == 2 and "relocation stream" in r.stderr, f"{cls}: a stream without its terminator is refused ({r.stderr.strip()[:90]})")
    open(badp, "wb").write(rom[:first + 0x100])
    r = run([a.cli, "build", "--recipe", recipe, "--rom", badp, "--blob", bp, "--syms", ref_syms, "--out", out_bad])
    check(r.returncode == 2 and "too short" in r.stderr, f"{cls}: a truncated ROM is refused ({r.stderr.strip()[:60]})")

    # 5. the real proof: N64Recomp on both
    if a.n64recomp:
        outs = {}
        for tag, blobf, symsf in (("static", ref_blob, ref_syms), ("cpp", os.path.join(out, "blob.bin"), os.path.join(out, "syms.toml"))):
            d = os.path.join(work, "n64r-" + tag)
            shutil.rmtree(d, ignore_errors=True)
            os.makedirs(d)
            shutil.copy(blobf, os.path.join(d, "codeblob.bin"))
            shutil.copy(symsf, os.path.join(d, "syms.toml"))
            cfg = n64recomp_config(cls, spec, d, "host.toml", "codeblob.bin", "syms.toml", "RecompiledFuncs")
            r = run([a.n64recomp, cfg], cwd=d)
            warn = sum(1 for l in r.stdout.splitlines() if l.startswith("[Warn]"))
            check(r.returncode == 0 and os.path.isdir(os.path.join(d, "RecompiledFuncs")), f"{cls}: N64Recomp on the {tag} input ({warn} warnings)")
            outs[tag] = os.path.join(d, "RecompiledFuncs")
        if all(os.path.isdir(v) for v in outs.values()):
            cmp = filecmp.dircmp(outs["static"], outs["cpp"])
            n = len(os.listdir(outs["static"]))
            ok = not (cmp.left_only or cmp.right_only or cmp.diff_files or cmp.funny_files)
            if ok:  # dircmp is shallow-by-stat first; confirm by content
                ok = all(same_file(os.path.join(outs["static"], f), os.path.join(outs["cpp"], f)) for f in os.listdir(outs["static"]))
            check(ok, f"{cls}: generated C identical ({n} files, static vs C++-prepared input)")
        total = sum(os.path.getsize(os.path.join(outs["static"], f)) for f in os.listdir(outs["static"])) if os.path.isdir(outs["static"]) else 0
        print(f"     RecompiledFuncs: {total / 1e6:.1f} MB")

    # 6. ROM-free scan of the committed recipe
    if a.scan:
        tool = a.scan_tool
        args = PY + [tool, rom_path, bp, os.path.join(out, "blob.bin"), rdir, "--sanity"]
        r = run(args)
        print("\n".join("     " + l for l in (r.stdout + r.stderr).strip().splitlines()[-6:]))
        check(r.returncode == 0, f"{cls}: scan_bundle (ROM, main blob, overlay blob vs the recipe directory) clean")
    return rom_path


def main(argv):
    a = type("A", (), {})()
    a.n64recomp = None
    a.scan = False
    a.keep = None
    a.rom = {}
    a.cli = None
    names = []
    it = iter(argv)
    for x in it:
        if x == "--n64recomp":
            a.n64recomp = os.path.abspath(next(it))
        elif x == "--scan":
            a.scan = True
        elif x == "--keep":
            a.keep = next(it)
        elif x == "--cli":
            a.cli = os.path.abspath(next(it))
        elif x == "--rom":
            k, v = next(it).split("=", 1)
            a.rom[k] = v
        else:
            names.append(x)
    names = names or list(G.CLASSES)
    cands = glob.glob(os.path.join(REPO, "decomp", "*", "recomp-host", "tools", "scan_bundle.py")) + glob.glob(os.path.join(COMMON, "host", "tools", "scan_bundle.py"))
    a.scan_tool = sorted(cands)[0] if cands else None
    if a.scan and not a.scan_tool:
        sys.exit("no scan_bundle.py found")
    a.work = a.keep or tempfile.mkdtemp(prefix="overlay-rom-test-")
    os.makedirs(a.work, exist_ok=True)
    a.cli = a.cli or G.build_cli(a.work)
    for cls in names:
        test_class(cls, a)
    if not a.keep:
        shutil.rmtree(a.work, ignore_errors=True)
    print(f"\n{'ALL PASS' if not FAILS else str(len(FAILS)) + ' FAILED'}")
    sys.exit(1 if FAILS else 0)


if __name__ == "__main__":
    main(sys.argv[1:])
