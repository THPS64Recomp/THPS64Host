// ROM versions and code classes (docs: docs/internals/versions.md).
//
// A ROM version is a row of decomp/common/games.toml (hashes, header, geometry); a code class is a
// set of recompiled functions (one generated payload) that one or more versions run. The host never
// asks "which version": it reads names from thps::sym() (build/gen/thps_versions.h, generated, keyed
// by symbol name) and facts from thps::version(). Adding a version = rows and data files, no host edit.
#pragma once
#include <cstdint>
#include <filesystem>
#include <string>
#include <string_view>

#include "recomp.h"
#include "librecomp/overlays.hpp"
#include "librecomp/sections.h"
#include "thps_versions.h"   // generated by tools/gen_versions.py

namespace thps {

// A front-end overlay of a code class (games with game::has_overlays; versions/<class>/overlay_table.inc, decomp/common/overlay_recomp.py):
// ROM offset and size of the screen's code blob, offset of its pre-linked copy in the class's code blob, its fake link base.
struct OverlayInfo { const char* name; uint32_t rom, size, blob_off, fake_base; };

// One linked payload (the generated C of a code class, compiled with its own name prefix).
struct Payload {
    const char* code_class;
    SectionTableEntry* sections;
    size_t num_sections;
    int* overlay_sections_by_index;
    size_t num_overlay_sections;
    void (*entrypoint)(uint8_t* rdram, recomp_context* ctx);   // the class's Boot_Entry
    const OverlayInfo* overlays = nullptr;   // the class's front-end screens (src/hooks.cpp maps them when DMA'd); none for THPS1
    size_t num_overlays = 0;
    const void* jit_begin = nullptr;   // LiveRecomp payload: the JIT code object (crash reports name its frames by range)
    const void* jit_end = nullptr;
};
struct PayloadRegistrar {
    explicit PayloadRegistrar(const Payload& p);
};
const Payload* payload_for(std::string_view code_class);   // nullptr: not linked into this build
void register_payload(const Payload& p);                    // split build: the game library registers its payload at load time

namespace versions {

// What a ROM file turned out to be (header and hash only; nothing is stored or run).
struct Identity {
    bool is_rom = false;               // an N64 ROM in some byte order
    bool read_ok = false;
    std::string internal_name;         // header name (trimmed)
    char game_code[5] = {};
    uint8_t revision = 0;
    uint64_t xxh3 = 0;
    char sha1[41] = {};                // of the big-endian image (what ROM databases list), when is_rom
    const VersionInfo* match = nullptr;     // hash matched this version
    const VersionInfo* by_header = nullptr;  // header (name/code/revision) matches this version, hash does not
    bool looks_like_game = false;      // header name starts with game::header_prefix: some version of this game
};
Identity identify(const std::filesystem::path& rom);

const VersionInfo* find(std::string_view id_or_game_id);        // games.toml row or game_id
bool runnable(const VersionInfo& v);                            // status Supported and its payload is linked
const char* region_name(const VersionInfo& v);                  // "USA", "Europe", ...
std::string describe(const VersionInfo& v);                     // "USA v1.1 (4900b6c9..., header revision 1)"
std::string supported_list();                                   // one line per runnable version

// The running version. activate() before recomp::start_game (main thread): selects the payload, registers
// its sections with librecomp and the crash log. sym() / version() are valid from then on.
void activate(const VersionInfo& v);
const VersionInfo* active();                                    // nullptr until activate()
int tv_type();                                                  // osTvType to write: --tv, else the version's tv_default
extern int tv_override;                                         // -1, else 0 PAL / 1 NTSC / 2 MPAL (--tv)

}  // namespace versions

// ROM file check (src/rom_check.cpp): `error` is a recomp::RomValidationError value (0 = Good: the file is a
// version this build runs, `version` says which); `text` is the message for users, naming what the file is.
// What a ROM offered to the first-run flow turned out to be. One distinct message each (listed in docs/SETUP.md, "First launch"); the split build's
// "runnable" means the app holds a recipe to build that very version.
enum class RomVerdict {
    Ok,           // a version this app can build
    ReadError,    // the file could not be opened or read
    NotARom,      // read fine, not an N64 ROM (wrong magic, too small or too big, an archive...)
    NotGame,      // an N64 ROM of another game
    WrongVersion, // this game, but no known dump: modified, damaged or another release
    NoRecipe,     // a known release of the game, but this app has no recipe for it (yet)
};

struct RomCheck {
    int error = 0;
    RomVerdict verdict = RomVerdict::Ok;
    versions::Identity id;
    const VersionInfo* version = nullptr;
    std::string text;
};
RomCheck check_rom_file(const std::filesystem::path& rom);

const VersionInfo& version();    // the active version (activate() first)
const SymTable& sym();           // its code class's names -> addresses / offsets

// Call a recompiled guest function by its (class-specific) address, as recompiled code does for jalr.
inline void call_guest(uint32_t vram, uint8_t* rdram, recomp_context* ctx) { get_function((int32_t)vram)(rdram, ctx); }

}  // namespace thps
