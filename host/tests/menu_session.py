"""The in-game settings menu sessions of the THPS recomp regression suite (shared by THPS1-3; each game's scenarios.py appends them).

Data only; the steps (ui, ui_state, ui_never, ui_input, ui_frame, file_exists, file_contains) are in run.py. They need a build with
THPS_MENU (the default; `--features` says menu=1) and skip otherwise. No references: nothing here depends on which screen of the game
is behind the menu, only on what the menu draws and what it saves. A fresh settings folder per run.

  menu         first launch: the hint shows once and writes ui-hint-shown; Esc opens the menu over the game (composited frame), Esc closes;
               the pad is blocked from the game while it is open and reaches it after; mouse clicks change Show FPS, MSAA, Aspect, Resolution and Frame Rate and
               write general.cfg / graphics.cfg; the pad's Back opens, D-pad / LB / RB navigate, A picks the N64 layout, B closes, the
               volume slider moves (a click on its track, then the D-pad); the settings are written to controls.cfg / general.cfg.
  menu-hud     the HUD Placement radio (Graphics tab) writes graphics.cfg hud=... and the renderer gets it; so does the Two-Player Split
               Screen radio (split=original|wide).
  menu-reload  a new process on the same folder: every setting persisted, and the hint does not show again.
  menu-controls  the Controls tab's rebinding (v0.2): a slot clicked, then a virtual pad button / key / trigger binds it (a swap when
               another action had it), live at once and saved to controls.cfg (preset = custom, a .bak kept); Esc / Back / the 5 s
               timeout cancel; Backspace empties a slot; Default resets a row; a layout preset resets everything; the same by pad only;
               changed slots are marked (`ui state` marked=...) and Reset all (asked first) puts the layout back.
  menu-controls-reload  a new process on the same folder: the rebinding persisted and works.
  menu-controls-row  Default on one row of a swap takes its button back from the other row and gives that row what it gave up.
  menu-controls-base(-reload)  N64, one slot customised, a restart: the marks, a row's Default and Reset all still use the N64 layout.
  menu-ports   the Controllers list: two virtual pads, Swap players, Player 1 / Player 2 per pad, the live "pressed" indicator, and
               a single pad on player 2 with the keyboard alone on player 1.
"""

