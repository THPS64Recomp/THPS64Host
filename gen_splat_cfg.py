"""Generate the two splat configs (boot = real ROM, main = inflated image) from games.toml.

  config/<game>.boot.yaml  header, IPL3, boot segment (entry stub, libultra .rodata, .text,
                           .data, .bss), chunk table + ERZ chunks + asset tree + any data
                           after the tree + zero tail as `bin`
  config/<game>.main.yaml  the inflated image at main_vram: .rodata | .text | RSP ucode
                           (`textbin`) | .text | .data | .bss

Needs the ROM to read the chunk table and the end of the asset tree.
Run once per game; the generated yaml is committed (it holds offsets only).

usage: python3 -I decomp/common/gen_splat_cfg.py --game thps2 ROM.z64 OUTDIR
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # -I drops it
import thps_unpack  # noqa: E402
import thpsgame  # noqa: E402

BOOT_ENTRY_END = 0x1070      # entry stub + 2 pad words; libultra .rodata follows
BOOT_TEXT_ROM = 0x1470       # boot main (0x80000870)


def h(x):
    return f"0x{x:X}"


def boot_yaml(g, rom):
    chunks = thps_unpack.chunk_spans(rom, g.table)
    root = struct.unpack_from(">I", rom, g.root_ptr)[0] & 0x0FFFFFFF
    n = struct.unpack_from(">I", rom, root)[0]
    tree_end = root + struct.unpack_from(f">{n + 1}I", rom, root + 4)[-1]
    nz = len(rom.rstrip(b"\0"))
    data_rom = g.boot_rom + g.boot_data_vram - g.boot_vram
    bss_size = g.main_vram - g.boot_end
    L = [f"# GENERATED by decomp/common/gen_splat_cfg.py from games.toml - splat config for the real ROM",
         f"# ({g.title}): header, IPL3, uncompressed boot segment, everything after as bin.",
         f"name: {g.title}", f"sha1: {g.rom_sha1}", "options:",
         f"  basename: {g.name}", "  target_path: baserom.z64", "  base_path: ..", "  platform: n64",
         "  compiler: IDO", "  asm_path: asm/boot", "  asset_path: assets/boot", "  build_path: build",
         f"  ld_script_path: linker_scripts/{g.name}.ld",
         "  undefined_funcs_auto_path: linker_scripts/boot_undefined_funcs_auto.txt",
         "  undefined_syms_auto_path: linker_scripts/boot_undefined_syms_auto.txt",
         "  symbol_addrs_path:", "    - symbols/boot.txt",
         "  find_file_boundaries: False", "  migrate_rodata_to_functions: False", "  create_c_files: False",
         "  o_as_suffix: True", "  mnemonic_ljust: 10", "  rom_address_padding: True", "  ld_bss_is_noload: True",
         "segments:", "  - name: header", "    type: header", "    start: 0x0",
         "  - name: ipl3", "    type: bin", "    start: 0x40",
         "  - name: boot", "    type: code", f"    start: {h(g.boot_rom)}", f"    vram: 0x{g.boot_vram:08X}",
         f"    bss_size: {h(bss_size)}          # 0x{g.boot_end:08X}..0x{g.main_vram:08X}, cleared by the entry stub",
         "    subsegments:",
         f"      - [{h(g.boot_rom)}, hasm, entry] # entry stub: sp, clear boot BSS, jal boot main (+2 pad words)",
         f"      - {{ start: {h(BOOT_ENTRY_END)}, type: rodata, name: rodata, linker_section_order: .text }}",
         f"      - [{h(BOOT_TEXT_ROM)}, asm, text]   # loader main, ERZ decoders, libultra (IDO)",
         f"      - [{h(data_rom)}, data, data] # 0x{g.boot_data_vram:08X}",
         f"      - {{ start: {h(g.root_ptr)}, type: bss, vram: 0x{g.boot_end:08X}, name: bss }}",
         f"  - [{h(g.root_ptr)}, bin, main_table]      # asset root word + chunk table"]
    for i, (a, span) in enumerate(chunks):
        L.append(f"  - [{h(a)}, bin, main_chunk{i:02d}]     # ERZ m{g.code_method} -> 0x{g.main_vram + i * g.stride:08X}")
    chunk_end = chunks[-1][0] + chunks[-1][1]
    if root != chunk_end:
        L.append(f"  - [{h(chunk_end)}, bin, pad_{chunk_end:X}]       # {root - chunk_end} pad byte(s): assets start 2-aligned")
    L.append(f"  - [{h(root)}, bin, assets]          # container tree: {n} packs of 16 KiB ERZ/raw pieces")
    if nz > tree_end:
        L.append(f"  - [{h(tree_end)}, bin, post_tree]       # data after the tree's last container (THPS2/3: front-end overlay)")
    L.append(f"  - [{h(max(nz, tree_end))}, bin, rom_tail]       # zero fill to the end of the ROM")
    L.append(f"  - [{h(g.rom_size)}]")
    return "\n".join(L) + "\n"


def main_yaml(g):
    (t0, _), (t1, _) = g.main_text
    uc = sorted(g.ucode_ranges(), key=lambda u: u[1])
    text2 = g.main_text[1][0]
    rel = lambda v: v - g.main_vram
    L = [f"# GENERATED by decomp/common/gen_splat_cfg.py from games.toml - splat config for the",
         f"# *inflated main image* of {g.title}, loaded at 0x{g.main_vram:08X}.",
         f"name: {g.title} main image", f"sha1: {g.main_sha1}   # of the decompressed image",
         "options:", f"  basename: {g.name}_main", "  target_path: baserom.main.bin", "  base_path: ..",
         "  platform: n64", "  compiler: GCC", '  section_order: [".rodata", ".text", ".data", ".bss"]',
         "  asm_path: asm/main", "  asset_path: assets/main", "  build_path: build",
         f"  ld_script_path: linker_scripts/{g.name}_main.ld",
         "  undefined_funcs_auto_path: linker_scripts/main_undefined_funcs_auto.txt",
         "  undefined_syms_auto_path: linker_scripts/main_undefined_syms_auto.txt",
         "  symbol_addrs_path:", "    - symbols/boot.txt      # libultra & loader live in the boot segment",
         "    - symbols/main.txt", "  find_file_boundaries: False", "  migrate_rodata_to_functions: False",
         "  create_c_files: False", "  ld_bss_is_noload: True", "  o_as_suffix: True", "  mnemonic_ljust: 10",
         "  rom_address_padding: True", "  generate_asm_macros_files: True",
         "segments:", "  - name: main", "    type: code", "    start: 0x0", f"    vram: 0x{g.main_vram:08X}",
         f"    bss_size: {h(g.game_bss_end - g.main_end)}          # 0x{g.main_end:08X}..0x{g.game_bss_end:08X}",
         "    subsegments:", "      - [0x0000, rodata, rodata]", f"      - [{h(rel(t0))}, asm, text]"]
    for name, v, sz in uc:
        L.append(f"      - [{h(rel(v))}, textbin, rsp_{name}_text]    # 0x{v:08X} ({h(sz)})")
    L += [f"      - [{h(rel(text2))}, asm, text2]", f"      - [{h(rel(g.main_data_vram))}, data, data]",
          f"      - {{ start: {h(g.main_size)}, type: bss, vram: 0x{g.main_end:08X}, name: bss }}",
          f"  - [{h(g.main_size)}]"]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    g, args = thpsgame.from_argv(sys.argv[1:])
    rom = open(args[0], "rb").read()
    out = args[1]
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, f"{g.name}.boot.yaml"), "w").write(boot_yaml(g, rom))
    open(os.path.join(out, f"{g.name}.main.yaml"), "w").write(main_yaml(g))
    print(f"wrote {out}/{g.name}.{{boot,main}}.yaml")
